def __getattr__(name: str):
    # audio_out imports sounddevice/soundfile, which no metadata command needs.
    if name in {
        "AudioPlaybackSession",
        "AudioSink",
        "NullAudioPlayer",
        "PlaybackResult",
        "SoundDevicePlayer",
        "StreamingAudioSink",
        "WavFileSink",
    }:
        from . import audio_out

        return getattr(audio_out, name)
    if name in {"PipelineResult", "VoicePipeline"}:
        from . import pipeline

        return getattr(pipeline, name)
    if name in {
        "AssistantRuntime",
        "DefaultRuntimeToolRouter",
        "RuntimeOptions",
        "RuntimeToolRouter",
    }:
        from .runtime import (
            AssistantRuntime,
            DefaultRuntimeToolRouter,
            RuntimeOptions,
            RuntimeToolRouter,
        )

        return {
            "AssistantRuntime": AssistantRuntime,
            "DefaultRuntimeToolRouter": DefaultRuntimeToolRouter,
            "RuntimeOptions": RuntimeOptions,
            "RuntimeToolRouter": RuntimeToolRouter,
        }[name]
    if name in {
        "ResolvedVoiceRuntimeConfig",
        "VoiceRuntimeBundle",
        "VoiceRuntimeWarmupError",
        "VoiceRuntimeWarmupResult",
        "build_voice_runtime",
        "resolve_voice_runtime_config",
        "warm_up_voice_runtime",
    }:
        from .voice_runtime import (
            ResolvedVoiceRuntimeConfig,
            VoiceRuntimeBundle,
            VoiceRuntimeWarmupError,
            VoiceRuntimeWarmupResult,
            build_voice_runtime,
            resolve_voice_runtime_config,
            warm_up_voice_runtime,
        )

        return {
            "ResolvedVoiceRuntimeConfig": ResolvedVoiceRuntimeConfig,
            "VoiceRuntimeBundle": VoiceRuntimeBundle,
            "VoiceRuntimeWarmupError": VoiceRuntimeWarmupError,
            "VoiceRuntimeWarmupResult": VoiceRuntimeWarmupResult,
            "build_voice_runtime": build_voice_runtime,
            "resolve_voice_runtime_config": resolve_voice_runtime_config,
            "warm_up_voice_runtime": warm_up_voice_runtime,
        }[name]
    raise AttributeError(name)


